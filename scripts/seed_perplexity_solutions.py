def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--update", action="store_true",
                        help="Пересоздать существующие записи по title")
    args = parser.parse_args()

    with db_session() as db:
        # Найдём категорию «business»
        biz = db.query(SolutionCategory).filter_by(slug="business").first()
        if not biz:
            print("ERROR: SolutionCategory slug='business' не найдена. "
                  "Запусти сначала seed_orchestra_solutions.py или другой скрипт "
                  "который создаёт базовые категории.")
            sys.exit(1)

        added = 0
        updated = 0
        skipped = 0

        for tpl in SOLUTIONS:
            existing = db.query(Solution).filter_by(
                title=tpl["title"], category_id=biz.id).first()
            if existing and not args.update:
                skipped += 1
                continue

            stage = {
                "id": "research",
                "label": "Глубокий ресёрч",
                "type": "perplexity_research",
                "model": "sonar-reasoning-pro",
                "search_context": "high",
                "max_tokens": 16000,
                "temperature": 0.2,
                "fix_price_kop": tpl["price_kop"],
                "query": tpl["prompt_tpl"],
            }
            if tpl.get("recency"):
                stage["search_recency_filter"] = tpl["recency"]
            orch = {
                "stages": [stage],
                "input_hint": tpl["input_hint"],
                "default_model": "sonar-reasoning-pro",
                "final_stage_id": "research",
            }

            if existing:
                existing.description = tpl["description"]
                existing.short_summary = tpl["short_summary"]
                existing.price_tokens = tpl["price_kop"]
                existing.subcategory = tpl["subcategory"]
                existing.tags = tpl["tags"]
                existing.is_featured = tpl["is_featured"]
                existing.orchestra_json = json.dumps(orch, ensure_ascii=False)
                existing.is_active = True
                updated += 1
                print(f"  ↻ {tpl['title']}")
            else:
                s = Solution(
                    category_id=biz.id,
                    title=tpl["title"],
                    description=tpl["description"],
                    short_summary=tpl["short_summary"],
                    price_tokens=tpl["price_kop"],
                    subcategory=tpl["subcategory"],
                    tags=tpl["tags"],
                    is_featured=tpl["is_featured"],
                    orchestra_json=json.dumps(orch, ensure_ascii=False),
                    is_active=True,
                    sort_order=1000 + added,  # выше старых
                )
                db.add(s)
                added += 1
                print(f"  + {tpl['title']}  ({tpl['price_kop']/100:.0f} ₽)")

        db.commit()
        print()
        print(f"Готово: добавлено {added}, обновлено {updated}, пропущено {skipped}.")


if __name__ == "__main__":
    main()

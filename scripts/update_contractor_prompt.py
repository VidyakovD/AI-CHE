"""
Одноразовый: обновляет промпт research-stage в Solution #36 (Проверка контрагента).

Юзер ввёл ИНН физлица/ИП (12 цифр), Perplexity сразу отказался: «это
ИНН физлица, не организации». Ответ обрезался, юзер не получил ничего.

Фикс: промпт явно учитывает все 3 формата контрагентов (юрлицо/ИП/физлицо),
велит не отказываться даже при отсутствии данных, а давать рекомендации.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from server.db import db_session
from server.models import Solution


NEW_QUERY = """Ты — аналитик-консультант. Сделай досье на контрагента и дай рекомендацию.

Данные о контрагенте от юзера:
{input}

ВАЖНО про формат ИНН:
- 10 цифр → ИНН юридического лица (ООО / АО / ПАО). Ищи в ЕГРЮЛ.
- 12 цифр → ИНН физического лица или ИП. Ищи в ЕГРИП и налоговой базе.
  В РФ многие реальные контрагенты — ИП. Это НЕ повод отказываться от проверки.
- Если введено название → найди ИНН через поиск, потом проверяй.

Если в открытых источниках мало данных — это НОРМАЛЬНО для малого бизнеса/новых
компаний. Не отказывайся, выдай что есть + рекомендуй где ещё проверить.
НИКОГДА не отвечай «не могу подготовить отчёт». Всегда выдавай структуру.

Структура отчёта (markdown, чёткие заголовки H2):

## Базовое
- Тип: ЮЛ / ИП / физлицо
- Полное наименование (для ЮЛ) или ФИО (для ИП/физлица)
- ИНН, ОГРН (или ОГРНИП), дата регистрации, статус (действующий/ликвидирован)
- Юр/фактический адрес
- Бенефициары и руководство (для ЮЛ — учредители с долями)
- Виды деятельности (ОКВЭД)

## Финансы (если данные доступны)
- Выручка за последние 3 года (источник: ФНС / БФО)
- Чистая прибыль / убыток
- Налоговая нагрузка
- Кредитный рейтинг (если ЮЛ)
- Если данных нет (малый бизнес / новый) — отметь и порекомендуй что запросить
  у контрагента напрямую (балансы, оборотки, рекомендательные письма от банков)

## Юр-риски
- Судебная практика 2024-2025: количество дел, в каких ролях (истец/ответчик)
- Самые крупные дела с суммами и статусом
- Банкротства связанных лиц
- Аресты имущества
- Открытые исполнительные производства (ФССП)
- Налоговые споры

## Репутация
- Упоминания в СМИ (релевантные за 2023-2025)
- Отзывы клиентов / партнёров (если есть в открытых источниках)
- Участие в гос-закупках / тендерах
- Связи с одиозными лицами или санкционными списками

## Рекомендация
Дай ИТОГОВУЮ оценку 1-3 предложениями:
- 🟢 БЕЗОПАСНО — заключайте сделку
- 🟡 С ОГОВОРКАМИ — что нужно дополнительно проверить
- 🔴 РИСКОВАННО — конкретные red flags

С обязательным учётом контекста сделки (партнёрство / купля / инвестор / etc)
и размера (чем больше сумма — тем строже критерии).

## Источники
Минимум 5 ссылок с описанием (ЕГРЮЛ, kad.arbitr.ru, fssp.gov.ru, СПарк, СМИ, etc).
Если ссылки не нашёл — укажи где сам юзер может проверить (URL + краткая инструкция).
"""


def main():
    with db_session() as db:
        s = db.query(Solution).filter_by(id=36).first()
        if not s:
            print("Solution #36 not found")
            return
        orch = json.loads(s.orchestra_json or "{}")
        stages = orch.get("stages") or []
        updated = 0
        for st in stages:
            if st.get("type") == "perplexity_research":
                st["query"] = NEW_QUERY
                updated += 1
        if updated == 0:
            print("No perplexity_research stages found")
            return
        s.orchestra_json = json.dumps(orch, ensure_ascii=False)
        db.commit()
        print(f"✅ Updated {updated} stage(s) in Solution #36 «{s.title}»")


if __name__ == "__main__":
    main()

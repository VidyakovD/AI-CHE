def main() -> None:
    Base.metadata.create_all(bind=engine)
    apply_lightweight_migrations()

    with db_session() as db:
        # Гарантируем категорию
        cat = db.query(SolutionCategory).filter_by(slug="business").first()
        if not cat:
            cat = SolutionCategory(slug="business", title="Бизнес-решения",
                                    sort_order=10)
            db.add(cat); db.commit(); db.refresh(cat)

        for pilot in PILOTS:
            sol = (db.query(Solution)
                     .filter_by(category_id=cat.id, title=pilot["title"]).first())
            orchestra_json = json.dumps(pilot["orchestra"], ensure_ascii=False,
                                         separators=(",", ":"))
            if sol:
                sol.orchestra_json = orchestra_json
                sol.description = pilot["description"]
                sol.price_tokens = pilot["price_tokens"]
                sol.is_active = True
                print(f"  ↻ обновлено: {pilot['title']}")
            else:
                sol = Solution(
                    category_id=cat.id,
                    title=pilot["title"],
                    description=pilot["description"],
                    price_tokens=pilot["price_tokens"],
                    is_active=True,
                    orchestra_json=orchestra_json,
                )
                db.add(sol)
                print(f"  + создано: {pilot['title']}")
        db.commit()
        print(f"\n✅ Готово. Установлено {len(PILOTS)} orchestra-решений в категории «Бизнес-решения».")


if __name__ == "__main__":
    main()
